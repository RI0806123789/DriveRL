# ---------------------------------------------------------------------------
# 広域プリセットについて（金沢）
# ---------------------------------------------------------------------------
# 「金沢市全部」を求められて実測した結果の記録。同じ検討を繰り返さないために残す。
#
# 面積を増やすと**すべてが線形に増える**（中心は香林坊で固定して実測）:
#
#   | 半径 | 面積 | ノード | 灯器(全交差点) | 建物 | map | frame | 20Hz | 1step |
#   |---|---|---|---|---|---|---|---|---|
#   |  400m |   0.6km² |     92 |    156 |    922 |  0.2MB |  15KB | 0.3MB/s |  3.5ms |
#   | 1500m |   9km²   |  1,501 |  3,640 |  8,729 |  2.6MB |  22KB | 0.4MB/s |  5.1ms |
#   | 3000m |  36km²   |  6,651 | 18,803 | 16,618 |  8.5MB |  51KB | 1.0MB/s |  7.4ms |
#   | 6000m | 144km²   | 19,493 | 55,714 | 35,607 | 23.5MB | 123KB | 2.4MB/s | 11.0ms |
#
# **金沢市の行政区域は 468km²**（南北約 30km・東西約 25km）で、正方形の bbox で
# 覆うには半径 15,000m が要る。上の傾きから外挿すると:
#   map 147MB / frame 770KB（15MB/s の連続配信）/ 占有グリッド 863MB / 建物 22 万件
# となり、**現在の設計では動かない**。効いてくる制約は次の 3 つ:
#
#   1. `frame.signals` は map.signals と同じ長さの配列を**毎フレーム**送る。
#      面積に比例して伸びるので、ここが最初に破綻する
#   2. 占有グリッド（GRID_CELL_SIZE = 1.0m）は面積に比例。半径 15km で 863MB
#      （レイキャスト専用。衝突判定は STRtree なので、粗くしても衝突精度は落ちない）
#   3. `map` メッセージは 1 通で全ジオメトリを送る。147MB は現実的でない
#
# 行政区域全体をやるなら、可視範囲だけを送るストリーミングへプロトコルごと
# 作り替える必要がある。**半径を増やすだけでは届かない。**
#
# --- 実際に採用した構成（半径 6000m + 信号は OSM タグ通り）の実測 ---
#   ノード 19,493 / エッジ 58,120 / 建物 35,607 / 灯器 2,736 / 標識 15,719
#   道路総延長 4,346km / 範囲 12.34km × 12.18km
#   キャッシュ 18.1MB / map メッセージ 18.2MB（うち標識 1.65MB = 9%）
#   ※ 標識は 27,583 基だった。うち 13,250 基は相互エッジ対による重複で、
#     code_review M-02 の修正（隣ノード単位での生成）で消えている。
#     同時に行き止まり 1,390 か所へ標識が立つようになったので差引 15,719 基。
#   frame 20KB → 20Hz で 0.40MB/s（**全交差点に信号を置くと 123KB / 2.4MB/s**）
#   MapIndex 構築 8.9 秒 / 占有グリッド 12,421 × 12,266 = 145MB（建物セル率 5.0%）
#   1 ステップ  4 台 4.43ms（11.3 倍速）/ 16 台 5.58ms（9.0 倍速）
#              64 台 18.07ms（2.8 倍速）※銀座 400m の 64 台は 13.22ms（3.8 倍速）
#
# ★ 信号をタグ通りにしたのが効いている。灯器 55,714 -> 2,736 で
#   frame が 123KB -> 20KB になり、**400m プリセット（15KB）とほぼ同じ**になった。
#   広域化で重くなるのは「毎フレーム送るもの」であって、マップの広さ自体ではない。
#
# --- 広域ゆえに残っている代償 ---
#   1. 経路を 1 本張るのが 400m マップより桁違いに重い。**支配項は 2 つある。**
#      ここには長らく「`world._random_route()` が 54ms」とだけ書いてあったが、
#      この 54ms は「ノード対 → 最短経路 → ポリライン」までしか含んでおらず、
#      実際の支配項だった `world._install_route()` が抜けていた（code_review M-01）。
#      `_install_route()` は経路上の信号と標識を突き合わせるところで
#      **全標識 × 全経路点**の密行列を作っており（当時の標識 27,583 基 × 経路 2,880 点
#      で 643MB）、respawn 1 回に 1,027ms（最悪 2,716ms）かかっていた。
#      これは `map/index.py` を STRtree で絞る形に直して解消した。
#
#      実測（同じ乱数列・同じ経路で比較。`MapIndex` は構築済み）:
#        respawn 1 台      旧 平均 1,027ms（最悪 2,716ms）→ 新 平均 63ms（最悪 194ms）
#        SimulationEnv(32) 旧 8.5 秒 → 新 0.5 秒
#      ※ 銀座（当時の標識 157 基）は 3.1ms → 2.1ms。もともと問題になっていない。
#
#      残った支配項は `networkx.bidirectional_dijkstra`（1 回 34ms）で、
#      1 台あたり 2 回呼ぶ（`random_node_pair` の到達可能性確認と本番の経路探索）。
#      ノード 19,493・エッジ 58,120 に対する素直なコストなので、これ以上詰めるなら
#      到達可能性をあらかじめ連結成分で持つなどの作り替えが要る。
#   2. **経路の 80% が物理的に到達不能**（120 本を実測）。
#      `MAX_EPISODE_STEPS = 4000` は 200 秒で、最高速 13.9m/s で**一度も止まらず**
#      走り続けても 2,780m しか進めない。それに対し経路長は中央 5,759m / 最大 12,551m。
#      銀座（中央 547m / 最大 1,051m）では到達不能な経路は 0%。
#      原因は `world.ROUTE_MIN_DISTANCE_M = 120` が下限だけで**上限が無い**こと。
#      広いマップでは無作為に選んだ 2 ノードが平均 6km 離れるため、こうなる。
#      **目的地報酬がほぼ入らないので、このままでは学習が成立しない。**
#      直すなら `random_node_pair` に最大距離を渡すのが最小の変更。

#: プリセット ID からプリセット定義への辞書。定義順（表示順）を保持する。
PRESETS: dict[str, MapPreset] = {p.id: p for p in _PRESET_LIST}

#: 既定で読み込むプリセット ID。
DEFAULT_PRESET_ID: str = _PRESET_LIST[0].id


def list_presets() -> list[MapPreset]:
    """定義順のプリセット一覧を返す（docs/protocol.md 2.1 の init.presets 用）。"""
    return list(_PRESET_LIST)


def get_preset(preset_id: str) -> MapPreset | None:
    """ID からプリセットを引く。未知の ID なら None（呼び出し側でエラー応答を作る）。"""
    return PRESETS.get(preset_id)
